roles.forEach(role => {
    const jsonPath = path.join(dataDir, `quiz_${role}.json`);
    const jsPath = path.join(dataDir, `quiz_${role}.js`);

    if (!fs.existsSync(jsonPath)) {
        console.error(`File not found: ${jsonPath}`);
        return;
    }

    console.log(`Processing quiz_${role}...`);
    const questions = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    let updatedCount = 0;

    questions.forEach(q => {
        let matched = false;
        for (const [key, value] of Object.entries(explanations)) {
            if (q.question.includes(key)) {
                q.analysis = value;
                matched = true;
                updatedCount++;
                break;
            }
        }
        if (!matched) {
            console.warn(`WARNING: No matching explanation found for question: "${q.question}"`);
            // Set a fallback generic analysis based on its category
            q.analysis = `该题属于 ${q.category} 范畴，标准答案为所列正确选项。请结合相关政策规章和校情进行学习。`;
        }
    });

    console.log(`Updated ${updatedCount}/${questions.length} questions in quiz_${role}.`);

    // Write back JSON
    fs.writeFileSync(jsonPath, JSON.stringify(questions, null, 2) + '\n', 'utf8');

    // Write back JS
    fs.writeFileSync(jsPath, `window.quizData = ${JSON.stringify(questions, null, 2)};\n`, 'utf8');
});

